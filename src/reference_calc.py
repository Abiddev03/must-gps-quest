"""ORIGINAL reference calculation (the "old behaviour"). It gets the distance wrong on purpose.

What it does:
  - reads pings in the order they ARRIVED (file order), not by their own timestamp
  - keeps every ping: no GPS noise filter, no duplicate removal
  - groups days by the UTC date instead of local midnight (UTC+9)
  - counts a segment only when both pings are inside the zone (this part is right)

Do not edit this file: the regression check runs against it to prove it fails here.
"""
import csv
from datetime import datetime

from src.geo import Map, distance_m


def load_pings(path):
    """Read pings in file (arrival) order. The `label` column is ignored on purpose."""
    with open(path) as f:
        return [{"ping_id": r["ping_id"], "driver_id": r["driver_id"],
                 "ts": datetime.fromisoformat(r["ts_utc"].replace("Z", "+00:00")),
                 "lat": float(r["lat"]), "lon": float(r["lon"])} for r in csv.DictReader(f)]


def distance_per_driver_day(pings, geo_map=None):
    """Return {(driver_id, date_str): km}."""
    m = geo_map or Map()
    totals, last = {}, {}
    for p in pings:  # arrival order
        key = (p["driver_id"], p["ts"].date().isoformat())  # UTC date
        totals.setdefault(key, 0.0)
        prev = last.get(key)
        if prev and m.in_zone(prev["lat"], prev["lon"]) and m.in_zone(p["lat"], p["lon"]):
            totals[key] += distance_m(prev["lat"], prev["lon"], p["lat"], p["lon"])
        last[key] = p
    return {k: v / 1000 for k, v in totals.items()}
